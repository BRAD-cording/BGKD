from stats_tests import bootstrap_ci, rank_biserial  # noqa: E402
from scipy import stats  # noqa: E402

RUNS = Path(r"C:\runs")
OUT = Path(r"c:\Users\HP\OneDrive\Desktop\Paper\paper\tables")
OUT.mkdir(parents=True, exist_ok=True)

BASELINES = {
    "full_nokd":     "Ours w/o KD",
    "own_baseline":  "Ours (base)",
    "hovernet":      "HoVer-Net (reimpl.)",
    "cellvit_sam256": "CellViT-256-SAM",
    "cellvit_t256":  "CellViT-256",
    "nulite_s":      "NuLite-S (official arch.)",
    "nulite_t":      "NuLite-T (t8 variant)",
    "ddbunet":       "DDBU-Net (repro.)",
}
DIR_OVERRIDE = {"own_baseline": {1: "w1_own_f1"},
                "cellvit_sam256": {f: f"cellvit_sam_f{f}" for f in (1, 2, 3)}}
METRICS = ["pq", "mpq_plus", "aji", "f1_det", "hd95", "bf1_2px"]
PCT = {"pq", "mpq_plus", "aji", "f1_det", "bf1_2px"}


def load_pooled(name: str) -> pd.DataFrame:
    dfs = []
    for f in (1, 2, 3):
        d = DIR_OVERRIDE.get(name, {}).get(f, f"{name}_f{f}")
        dfs.append(pd.read_csv(RUNS / d / "val_metrics.csv"))
    return pd.concat(dfs, ignore_index=True)


def safe_wilcoxon(d: np.ndarray) -> float:
    d = d[~np.isnan(d)]
    if d.size == 0 or not np.any(d != 0):
        return 1.0
    try:
        return float(stats.wilcoxon(d, zero_method="wilcox").pvalue)
    except (ValueError, np.linalg.LinAlgError):
        return 1.0


def holm(pvals):
    p = np.asarray(pvals, float)
    m = p.size
    order = np.argsort(p)
    out = np.empty(m)
    running = 0.0
    for rank, i in enumerate(order):
        running = max(running, (m - rank) * p[i])
        out[i] = min(1.0, running)
    return out


def paired(a: pd.DataFrame, b: pd.DataFrame, metric: str, seed=0, alpha=0.05):
    m = (a[["patch_id", "group", metric]]
         .merge(b[["patch_id", metric]], on="patch_id", suffixes=("_a", "_b"))
         .dropna(subset=[f"{metric}_a", f"{metric}_b"]))
    d_patch = (m[f"{metric}_a"] - m[f"{metric}_b"]).to_numpy()
    ga = m.groupby("group")[f"{metric}_a"].mean()
    gb = m.groupby("group")[f"{metric}_b"].mean()
    ok = ga.notna() & gb.notna()
    d = (ga[ok] - gb[ok]).to_numpy()
    rb, n_eff = rank_biserial(d)
    diff = float(d.mean())
    base = float(gb[ok].mean())
    rel = 100.0 * diff / base if base else np.nan
    lo, hi = bootstrap_ci(d, seed=seed, alpha=alpha)
    return dict(
        metric=metric, mean_a=float(ga[ok].mean()), mean_b=base,
        rel_improve_pct=rel, mean_diff=diff, ci_lo=lo, ci_hi=hi,
        p_group=safe_wilcoxon(d), p_patch_ref=safe_wilcoxon(d_patch),
        effect_rank_biserial=rb, n_group=int(ok.sum()), n_patch=int(len(m)),
        n_effective=n_eff)


def main():
    ours = load_pooled("full")
    rows_all = {}
    for base, disp in BASELINES.items():
        rows = [paired(ours, load_pooled(base), k) for k in METRICS]
        df = pd.DataFrame(rows)
        df["p_holm"] = holm(df["p_group"].to_numpy())
        df["significant"] = df["p_holm"] < 0.05
        rows_all[base] = df
        df.to_csv(OUT / f"stats_full_vs_{base}.csv", index=False)
        print(f"\n=== Full vs {disp} ===")
        show = df.copy()
        for c in ("p_group", "p_patch_ref", "p_holm"):
            show[c] = show[c].map(lambda v: f"{v:.3g}")
        print(show[["metric", "mean_diff", "ci_lo", "ci_hi", "p_group",
                    "p_holm", "effect_rank_biserial", "n_group",
                    "significant"]].to_string(index=False))

    # ---- LaTeX: PQ 与 mPQ+ 两行 × 各基线 ----
    lines = [
        "% auto-generated by run_stats.py — DO NOT EDIT NUMBERS",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Paired comparisons of Ours (full) against every baseline and "
        "ablation anchor. PanNuke v1 provides no slide provenance, so the primary "
        "test is a Wilcoxon signed-rank test on tissue-type means (19 groups; "
        "per-patch differences pooled over the three folds), Holm-corrected within "
        "each comparison over the six primary metrics; 95\\% CIs are tissue-level "
        "percentile bootstrap (10{,}000 resamples). HD95: negative difference = "
        "improvement (lower is better). $^{*}$: $p_{\\mathrm{Holm}}<0.05$.}",
        "\\label{tab:stats}", "\\small",
        "\\setlength{\\tabcolsep}{4.5pt}",
        "\\begin{tabular}{l ccc c}", "\\toprule",
        "Comparison & $\\Delta$ & 95\\% CI & $p_{\\mathrm{Holm}}$ & rank-biserial \\\\",
        "\\midrule",
    ]
    for metric, mlab in (("pq", "PQ (\\%)"), ("mpq_plus", "mPQ+ (\\%)")):
        first = True
        lines.append(f"\\multicolumn{{5}}{{l}}{{\\emph{{Metric: {mlab}}}}} \\\\")
        for base, disp in BASELINES.items():
            df = rows_all[base]
            r = df[df.metric == metric].iloc[0]
            scale = 100 if metric in PCT else 1
            star = "$^{*}$" if r.significant else ""
            lab = disp if first else f"\\quad {disp}"
            lines.append(
                f"{lab} & {r.mean_diff*scale:+.2f} & "
                f"[{r.ci_lo*scale:+.2f}, {r.ci_hi*scale:+.2f}] & "
                f"{r.p_holm:.3g}{star} & {r.effect_rank_biserial:+.2f} \\\\")
            first = False
        lines.append("\\midrule")
    lines = lines[:-1] + ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (OUT / "stats_table.tex").write_text("\n".join(lines), encoding="utf-8")
    print("\n[table] stats_table.tex")

    # 供正文引用 (全部 6 主指标, 与预注册族一致)
    facts = {}
    for base in BASELINES:
        for k in METRICS:
            r = rows_all[base]
            row = r[r.metric == k].iloc[0]
            facts[f"{base}_{k}"] = {c: (float(row[c]) if k != "significant" else bool(row[c]))
                                    for c in ("mean_diff", "ci_lo", "ci_hi",
                                              "p_group", "p_holm",
                                              "effect_rank_biserial")}
            facts[f"{base}_{k}"]["significant"] = bool(row["significant"])
    (PKG.parent.parent / "paper" / "stats_facts.json").write_text(
        json.dumps(facts, indent=2), encoding="utf-8")
    print("[saved] stats_facts.json")


if __name__ == "__main__":
    main()
